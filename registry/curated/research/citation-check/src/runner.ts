/**
 * @file runner.ts
 * @description The check itself. Each distinct page a document cites is read once, a few at a time. Classical first:
 * a claim whose words stand on its page is `exact`, with the sentence they stand in. A claim that is not is graded by
 * AgentOS's `CitationVerifier` against the page's sentences when the caller gives an embedding function (an NLI
 * function, when given too, turning a `supported` claim the page contradicts into `contradicted`), and is `not_found`
 * otherwise, with the sentences nearest it by shared words. Nothing that costs money is called unless the caller
 * passes it in; no search service is called at all.
 *
 * @module agentos/extensions/research/citation-check/runner
 */

import { exactSpan, sentenceSpans } from '@framers/agentos-ext-grounding-guard/values';
import { WebScraperService } from '@framers/agentos-ext-web-scraper';
import { lexicalNearest, locateQuote, normalizeForMatch, quoteFragments } from './match.js';
import { egressTransport, fetchTransport, originOf, pageKey, readPage, type EgressProfile, type PageRead, type PageScraper, type Transport } from './page.js';
import { CitationInputError, parseCitedClaims, type CitedClaimFormat } from './parse.js';
import { CITATION_VERDICTS, type CitationCheck, type CitationLogger, type CitationReport, type CitationVerdict, type CitedClaim, type EmbedFn, type NliFn, type PageStatus } from './types.js';

/** How a check runs. Every option has a default; none calls a paid service unless it is passed in. */
export interface CitationCheckOptions {
  /**
   * The `fetch` pages are requested with; the global one when left out. Pass one that applies your egress rules when
   * the documents come from people you do not trust. Not with `egress`.
   */
  fetch?: typeof globalThis.fetch;
  /**
   * Read pages through AgentOS's checked egress (`@framers/agentos/safety/egress`, from 0.13.120) with this policy
   * instead of `fetch`: `hosted` reaches public https addresses on port 443 alone, `local` any address.
   */
  egress?: EgressProfile;
  /**
   * The retry for a page that failed in a way a browser may mend: the web scraper pack's `WebScraperService` (`true`),
   * another scraper, or none (`false`). On by default only when neither `fetch` nor `egress` is given, since the
   * scraper's requests do not go through them.
   */
  fallback?: boolean | PageScraper;
  /** The deadline of one page's request, in milliseconds; 15,000 when left out. */
  timeoutMs?: number;
  /** The most bytes read of one page; 5,000,000 when left out. */
  maxBytes?: number;
  /** The most characters of text kept of one page; 300,000 when left out. */
  textBudget?: number;
  /** How many pages are read at once; 4 when left out. */
  concurrency?: number;
  /** The most distinct pages one check reads; 100 when left out. More is a {@link CitationInputError}. */
  maxPages?: number;
  /** The User-Agent sent; a browser's, generated by the web scraper pack, when left out. */
  userAgent?: string;
  /** The batch embedding function `CitationVerifier` grades with; with none, a claim not found word for word is `not_found`. */
  embedFn?: EmbedFn;
  /** `CitationVerifier`'s similarity for `supported`; its own default (0.6) when left out. */
  supportThreshold?: number;
  /** `CitationVerifier`'s similarity under which a claim is `unverifiable`; its own default (0.3) when left out. */
  unverifiableThreshold?: number;
  /** The NLI function `CitationVerifier` turns a contradicted `supported` claim with, such as grounding-guard's `createNliFunction()`. */
  nliFn?: NliFn;
  /** The most sentences of one page graded by embeddings, in page order; 2,000 when left out. */
  maxPassages?: number;
  /** How many nearest sentences a `not_found` claim shows; 3 when left out. */
  nearest?: number;
  /** Where the check writes its events. */
  logger?: CitationLogger;
  /** The caller's cancellation: the check stops and throws its reason. */
  signal?: AbortSignal;
  /** The clock of `checkedAt` and of each page's `readAt`; `Date.now` when left out. */
  now?: () => number;
}

/** Settings the check cannot run with. */
export class CitationSetupError extends Error {
  /** @param message - What is wrong. */
  constructor(message: string) {
    super(message);
    this.name = 'CitationSetupError';
  }
}

/** The options with their defaults, checked. */
interface Settings {
  timeoutMs: number;
  maxBytes: number;
  textBudget: number;
  concurrency: number;
  maxPages: number;
  maxPassages: number;
  nearest: number;
  now: () => number;
}

/** A whole number of at least `least`, or the default when left out. */
function whole(name: string, value: number | undefined, fallback: number, least: number): number {
  if (value === undefined) return fallback;
  if (!Number.isInteger(value) || value < least) throw new CitationSetupError(`${name} must be a whole number of at least ${least}`);
  return value;
}

/** The options' numbers with their defaults, refused when out of range. */
function settingsOf(options: CitationCheckOptions): Settings {
  if (options.fetch !== undefined && options.egress !== undefined) throw new CitationSetupError('pass fetch or egress, not both');
  if (options.egress !== undefined && options.egress !== 'hosted' && options.egress !== 'local') throw new CitationSetupError('egress must be hosted or local');
  for (const [name, value] of [['supportThreshold', options.supportThreshold], ['unverifiableThreshold', options.unverifiableThreshold]] as const) {
    if (value !== undefined && !(value >= 0 && value <= 1)) throw new CitationSetupError(`${name} must be between 0 and 1`);
  }
  return {
    timeoutMs: whole('timeoutMs', options.timeoutMs, 15_000, 1),
    maxBytes: whole('maxBytes', options.maxBytes, 5_000_000, 1),
    textBudget: whole('textBudget', options.textBudget, 300_000, 1),
    concurrency: whole('concurrency', options.concurrency, 4, 1),
    maxPages: whole('maxPages', options.maxPages, 100, 1),
    maxPassages: whole('maxPassages', options.maxPassages, 2_000, 1),
    nearest: whole('nearest', options.nearest, 3, 0),
    now: options.now ?? Date.now,
  };
}

/** The request the pages go through. */
async function transportOf(options: CitationCheckOptions, settings: Settings): Promise<Transport> {
  if (options.egress !== undefined) return egressTransport(options.egress, { timeoutMs: settings.timeoutMs, maxBytes: settings.maxBytes }, options.userAgent);
  return fetchTransport(options.fetch ?? ((input, init) => globalThis.fetch(input, init)), options.userAgent);
}

/** The fallback scraper, or null for none. */
function scraperOf(options: CitationCheckOptions): PageScraper | null {
  const fallback = options.fallback ?? (options.fetch === undefined && options.egress === undefined);
  if (fallback === false) return null;
  if (fallback === true) return new WebScraperService();
  return fallback;
}

/** Runs `work` over the items, at most `limit` at once, the answers in the items' order. */
async function eachLimited<T, R>(items: readonly T[], limit: number, work: (item: T) => Promise<R>): Promise<R[]> {
  const out = new Array<R>(items.length);
  let next = 0;
  const lane = async (): Promise<void> => {
    while (next < items.length) {
      const index = next;
      next += 1;
      out[index] = await work(items[index] as T);
    }
  };
  await Promise.all(Array.from({ length: Math.min(limit, items.length) }, lane));
  return out;
}

/** A check with its verdict and nothing else filled in. */
function bare(claim: CitedClaim, verdict: CitationVerdict): CitationCheck {
  return { line: claim.line, claim: claim.claim, url: claim.url, exact: claim.exact, verdict, grader: null, score: null, passage: null, nearest: [], note: null };
}

/** A page's text as the matcher reads it, with where each block starts in it. */
interface MatchText {
  text: string;
  starts: number[];
}

/** The page's blocks read with `normalizeForMatch` and joined by spaces, with each block's start. */
function matchTextOf(blocks: readonly string[]): MatchText {
  let text = '';
  const starts: number[] = [];
  for (const block of blocks) {
    if (text !== '') text += ' ';
    starts.push(text.length);
    text += normalizeForMatch(block);
  }
  return { text, starts };
}

/** The longest a passage a report shows runs, in characters. */
const PASSAGE_MAX = 600;

/** A passage held to {@link PASSAGE_MAX} characters. */
function clip(text: string): string {
  return text.length <= PASSAGE_MAX ? text : `${text.slice(0, PASSAGE_MAX - 1).trimEnd()}…`;
}

/** The sentence a claim's words stand in on the page, or the block when they run past one sentence; null when they do not stand there. */
function exactPassage(claim: string, page: PageRead, match: MatchText): string | null {
  const fragments = quoteFragments(claim);
  const span = locateQuote(match.text, fragments);
  if (span === null) return null;
  let index = match.starts.length - 1;
  while (index > 0 && (match.starts[index] ?? 0) > span.start) index -= 1;
  const block = page.blocks[index] ?? '';
  const first = fragments[0] ?? '';
  for (const { start, end } of sentenceSpans(block)) {
    const sentence = block.slice(start, end);
    if (exactSpan(normalizeForMatch(sentence), first) !== null) return clip(sentence);
  }
  return clip(block);
}

/** The first line of an error's message, held to 200 characters. */
function reasonOf(error: unknown): string {
  const message = error instanceof Error ? error.message : String(error);
  return (message.split('\n')[0] ?? '').slice(0, 200);
}

/** The `not_found` verdict with the nearest sentences. */
function lexical(claim: CitedClaim, page: PageRead, count: number, note: string | null): CitationCheck {
  const nearest = lexicalNearest(claim.claim, page.passages.map((passage) => passage.content), count);
  return { ...bare(claim, 'not_found'), grader: 'lexical', score: nearest[0]?.score ?? 0, passage: nearest[0]?.text ?? null, nearest, note };
}

/** Grades one page's claims that are not on it word for word through AgentOS's `CitationVerifier`. */
async function graded(claims: readonly CitedClaim[], page: PageRead, options: CitationCheckOptions, embedFn: EmbedFn, settings: Settings): Promise<CitationCheck[]> {
  const sources = page.passages.slice(0, settings.maxPassages);
  const { CitationVerifier } = await import('@framers/agentos/cognition/rag/citation/index');
  const verifier = new CitationVerifier({
    embedFn,
    ...(options.supportThreshold !== undefined ? { supportThreshold: options.supportThreshold } : {}),
    ...(options.unverifiableThreshold !== undefined ? { unverifiableThreshold: options.unverifiableThreshold } : {}),
    ...(options.nliFn !== undefined ? { nliFn: options.nliFn } : {}),
  });
  const result = await verifier.verify(
    claims.map((claim) => claim.claim),
    sources,
  );
  return claims.map((claim, index): CitationCheck => {
    const verdict = result.claims[index];
    if (verdict === undefined) throw new Error('the citation verifier answered fewer verdicts than claims');
    const source = verdict.sourceIndex === undefined ? undefined : sources[verdict.sourceIndex];
    return { ...bare(claim, verdict.verdict), grader: 'embedding', score: verdict.confidence, passage: source === undefined ? null : clip(source.content) };
  });
}

/**
 * Checks each cited claim against the page it cites, and reports the verdicts, the pages and a summary.
 *
 * @param claims - The claims, as {@link parseCitedClaims} gives them.
 * @param options - How to run; see {@link CitationCheckOptions}.
 * @returns The report: one check per claim in the claims' order, one status per distinct page.
 * @throws {CitationInputError} For a claim whose address is not http or https, or more distinct pages than `maxPages`.
 * @throws {CitationSetupError} For options out of range, or `egress` with an AgentOS that has no checked egress.
 * @throws The caller's cancellation reason, when `signal` aborts.
 */
export async function checkCitations(claims: readonly CitedClaim[], options: CitationCheckOptions = {}): Promise<CitationReport> {
  const settings = settingsOf(options);
  const checkedAt = new Date(settings.now()).toISOString();
  const keys = claims.map((claim) => {
    if (claim.url === null) return null;
    try {
      const url = new URL(claim.url);
      if (url.protocol === 'http:' || url.protocol === 'https:') return pageKey(claim.url);
    } catch {
      // Refused below.
    }
    throw new CitationInputError(`line ${claim.line}: ${JSON.stringify(claim.url)} is not an http or https address`);
  });
  const distinct = [...new Set(keys.filter((key): key is string => key !== null))];
  if (distinct.length > settings.maxPages) {
    throw new CitationInputError(`the document cites ${distinct.length} distinct pages; one check reads at most ${settings.maxPages}`);
  }
  options.signal?.throwIfAborted();

  let transport: Transport;
  try {
    transport = await transportOf(options, settings);
  } catch (error) {
    throw new CitationSetupError(reasonOf(error));
  }
  const scraper = distinct.length > 0 ? scraperOf(options) : null;
  const read = await eachLimited(distinct, settings.concurrency, (url) =>
    readPage(url, {
      transport,
      scraper,
      timeoutMs: settings.timeoutMs,
      maxBytes: settings.maxBytes,
      textBudget: settings.textBudget,
      now: settings.now,
      ...(options.signal ? { signal: options.signal } : {}),
      ...(options.logger ? { logger: options.logger } : {}),
    }),
  );
  const pages = new Map<string, PageRead>(distinct.map((url, index): [string, PageRead] => [url, read[index] as PageRead]));

  const checks: CitationCheck[] = claims.map((claim) => bare(claim, 'uncited'));
  const waiting = new Map<string, number[]>();
  claims.forEach((claim, index) => {
    const key = keys[index];
    if (key === null || key === undefined) return;
    const page = pages.get(key) as PageRead;
    if (page.status.outcome !== 'read') {
      checks[index] = bare(claim, page.status.outcome);
      return;
    }
    waiting.set(key, [...(waiting.get(key) ?? []), index]);
  });

  for (const [key, indexes] of waiting) {
    const page = pages.get(key) as PageRead;
    const match = matchTextOf(page.blocks);
    const rest: number[] = [];
    for (const index of indexes) {
      const claim = claims[index] as CitedClaim;
      const passage = exactPassage(claim.claim, page, match);
      if (passage === null) rest.push(index);
      else checks[index] = { ...bare(claim, 'exact'), grader: 'exact', score: 1, passage };
    }
    if (rest.length === 0) continue;
    const embedFn = options.embedFn;
    if (embedFn !== undefined) {
      const restClaims = rest.map((index) => claims[index] as CitedClaim);
      try {
        const verdicts = await graded(restClaims, page, options, embedFn, settings);
        rest.forEach((index, at) => {
          checks[index] = verdicts[at] as CitationCheck;
        });
        continue;
      } catch (error) {
        if (options.signal?.aborted) throw options.signal.reason;
        const reason = reasonOf(error);
        options.logger?.warn('citation_check.embedding_failed', { origin: originOf(key), claims: rest.length, error: reason });
        for (const index of rest) checks[index] = lexical(claims[index] as CitedClaim, page, settings.nearest, `embedding grader failed: ${reason}`);
        continue;
      }
    }
    for (const index of rest) checks[index] = lexical(claims[index] as CitedClaim, page, settings.nearest, null);
  }

  const statuses: PageStatus[] = distinct.map((url) => (pages.get(url) as PageRead).status);
  const counts = Object.fromEntries(CITATION_VERDICTS.map((verdict) => [verdict, 0])) as Record<CitationVerdict, number>;
  for (const check of checks) counts[check.verdict] += 1;
  return {
    checkedAt,
    grading: options.embedFn === undefined ? 'lexical' : 'embedding',
    checks,
    pages: statuses,
    summary: {
      claims: checks.length,
      pages: statuses.length,
      counts,
      uncited: checks.filter((check) => check.verdict === 'uncited').map((check) => ({ line: check.line, claim: check.claim })),
      unreachable: statuses.filter((status) => status.outcome !== 'read'),
    },
  };
}

/**
 * Parses a document's cited claims and checks them: {@link parseCitedClaims}, then {@link checkCitations}.
 *
 * @param text - Markdown, or a JSON array of claims.
 * @param options - The check's options, and `format` for the parser.
 */
export async function checkCitationDocument(text: string, options: CitationCheckOptions & { format?: CitedClaimFormat } = {}): Promise<CitationReport> {
  const { format, ...check } = options;
  return checkCitations(parseCitedClaims(text, { format: format ?? 'auto' }), check);
}
